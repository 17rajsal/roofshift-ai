class NumberedCanvas(canvas.Canvas):
    """Adds professional running headers and 'Page X of Y' footers to every page."""
    def __init__(self, *args, **kwargs):
        super(NumberedCanvas, self).__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_header_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "RoofShift AI — Solar Investment & Energy Optimization Report")
            self.drawRightString(612 - 54, 750, "CONFIDENTIAL & PRELIMINARY")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, 744, 612 - 54, 744)

        # Footer
        self.drawString(54, 36, "Generated by RoofShift AI | Intelligent Rooftop Solar Planning & Energy Optimization")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 54, 36, page_str)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 46, 612 - 54, 46)
        self.restoreState()

def generate_project_pdf_report(
    project_id: str, db: Session, notes: Optional[str] = None,
    scheduling_result: Optional[SchedulingOptimizationResponse] = None,
    include_load_shifting: bool = True,
    include_features: bool = True,
    include_scenarios: bool = True,
) -> GeneratedReport:
    """
    Builds a comprehensive, publication-grade PDF report using ReportLab.
    """
    project = db.query(Project).filter(Project.id == project_id).first()
    if not project:
        raise ValueError("Project not found.")

    buildings = db.query(Building).filter(Building.project_id == project_id).all()
    latest_run = db.query(OptimizationRun).filter(
        OptimizationRun.project_id == project_id
    ).order_by(OptimizationRun.created_at.desc()).first()
    activities = db.query(EnergyActivity).filter(EnergyActivity.project_id == project_id).all()

    # Ensure output directory exists
    os.makedirs(settings.REPORTS_DIR, exist_ok=True)
    timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
    clean_name = "".join(c if c.isalnum() else "_" for c in project.name)[:25]
    filename = f"RoofShift_Report_{clean_name}_{timestamp}_{uuid.uuid4().hex[:10]}.pdf"
    file_path = os.path.join(settings.REPORTS_DIR, filename)

    doc = SimpleDocTemplate(
        file_path,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()
    
    # Custom Palette
    c_forest = colors.HexColor("#123C32")
    c_emerald = colors.HexColor("#10B981")
    c_amber = colors.HexColor("#D97706")
    c_dark = colors.HexColor("#1E293B")
    c_muted = colors.HexColor("#64748B")
    c_light = colors.HexColor("#F8FAFC")

    # Typography styles
    style_title = ParagraphStyle(
        "CoverTitle", parent=styles["Normal"],
        fontName="Helvetica-Bold", fontSize=26, leading=32,
        textColor=c_forest, spaceAfter=8
    )
    style_subtitle = ParagraphStyle(
        "CoverSubtitle", parent=styles["Normal"],
        fontName="Helvetica", fontSize=13, leading=18,
        textColor=c_emerald, spaceAfter=20
    )
    style_h1 = ParagraphStyle(
        "Heading1_Custom", parent=styles["Heading1"],
        fontName="Helvetica-Bold", fontSize=16, leading=20,
        textColor=c_forest, spaceBefore=14, spaceAfter=8, keepWithNext=True
    )
    style_h2 = ParagraphStyle(
        "Heading2_Custom", parent=styles["Heading2"],
        fontName="Helvetica-Bold", fontSize=12, leading=16,
        textColor=c_forest, spaceBefore=10, spaceAfter=6, keepWithNext=True
    )
    style_body = ParagraphStyle(
        "Body_Custom", parent=styles["Normal"],
        fontName="Helvetica", fontSize=9.5, leading=13.5,
        textColor=c_dark, spaceAfter=6
    )
    style_body_bold = ParagraphStyle(
        "BodyBold_Custom", parent=styles["Normal"],
        fontName="Helvetica-Bold", fontSize=9.5, leading=13.5,
        textColor=c_dark, spaceAfter=6
    )
    style_caption = ParagraphStyle(
        "Caption_Custom", parent=styles["Normal"],
        fontName="Helvetica-Oblique", fontSize=8, leading=11,
        textColor=c_muted, spaceAfter=8
    )

    story = []

    # ================= COVER / TITLE =================
    story.append(Spacer(1, 20))
    story.append(Paragraph("RoofShift AI", style_subtitle))
    story.append(Paragraph("Solar Investment & Energy Optimization Report", style_title))
    story.append(Paragraph(
        f"<b>Organization:</b> {escape(project.organization_name)} &nbsp;|&nbsp; "
        f"<b>Location:</b> {escape(project.city)} &nbsp;|&nbsp; "
        f"<b>Date:</b> {datetime.utcnow().strftime('%B %d, %Y')}",
        style_body
    ))
    story.append(HRFlowable(width="100%", thickness=2, color=c_emerald, spaceAfter=15))

    # ================= 1. EXECUTIVE SUMMARY =================
    story.append(Paragraph("1. Executive Summary", style_h1))
    
    if latest_run:
        exec_text = (
            f"This preliminary solar engineering and financial assessment evaluates <b>{len(buildings)} candidate campus rooftops</b> "
            f"in <b>{escape(project.city)}</b> under an institutional capital expenditure ceiling of <b>INR {latest_run.budget_inr:,.0f}</b>. "
            f"Using satellite-derived climatological solar irradiance from NASA POWER and rigorous multiple-choice knapsack optimization, "
            f"RoofShift AI recommends deploying <b>{latest_run.total_capacity_kwp:.1f} kWp</b> of rooftop solar PV capacity. "
            f"This optimized portfolio generates an estimated <b>{latest_run.total_annual_generation_kwh:,.0f} kWh</b> of clean electricity annually, "
            f"saving <b>INR {latest_run.total_annual_savings_inr:,.0f}</b> in annual utility expenditure with an attractive capital recovery period "
            f"of <b>{latest_run.overall_payback_years if latest_run.overall_payback_years else 'N/A'} years</b> and displacing <b>{latest_run.avoided_co2_kg_annual:,.0f} kg CO2</b> annually."
        )
    else:
        exec_text = (
            f"Preliminary rooftop solar assessment for <b>{escape(project.name)}</b> across <b>{len(buildings)} buildings</b>. "
            f"Assessment incorporates location-specific solar irradiance and electricity demand models."
        )
    story.append(Paragraph(exec_text, style_body))

    # Key Metrics KPI Table
    if latest_run:
        kpi_data = [
            [
                Paragraph("<b>Total Budget</b>", style_body),
                Paragraph(f"INR {latest_run.budget_inr:,.0f}", style_body_bold),
                Paragraph("<b>Recommended Solar</b>", style_body),
                Paragraph(f"{latest_run.total_capacity_kwp:.1f} kWp", style_body_bold)
            ],
            [
                Paragraph("<b>Allocated Capex</b>", style_body),
                Paragraph(f"INR {latest_run.total_allocated_inr:,.0f}", style_body_bold),
                Paragraph("<b>Annual Generation</b>", style_body),
                Paragraph(f"{latest_run.total_annual_generation_kwh:,.0f} kWh", style_body_bold)
            ],
            [
                Paragraph("<b>Annual Bill Savings</b>", style_body),
                Paragraph(f"INR {latest_run.total_annual_savings_inr:,.0f}", style_body_bold),
                Paragraph("<b>Estimated Payback</b>", style_body),
                Paragraph(f"{latest_run.overall_payback_years} Years", style_body_bold)
            ],
            [
                Paragraph("<b>Annual CO2 Avoided</b>", style_body),
                Paragraph(f"{latest_run.avoided_co2_kg_annual:,.0f} kg CO2", style_body_bold),
                Paragraph("<b>Baseline Savings Lift</b>", style_body),
                Paragraph(f"+{latest_run.savings_lift_pct:.1f}%", style_body_bold)
            ]
        ]
        t_kpi = Table(kpi_data, colWidths=[120, 130, 120, 134])
        t_kpi.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), c_light),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(t_kpi)
        story.append(Spacer(1, 10))

    # ================= 2. CANDIDATE BUILDINGS INVENTORY =================
    story.append(Paragraph("2. Candidate Buildings & Rooftop Characteristics", style_h1))
    story.append(Paragraph(
        "Candidate roofs were surveyed for total surface footprint, usable mounting area, and visual shading obstructions.",
        style_body
    ))

    b_table_data = [
        ["Building Name", "Category", "Gross Area", "Usable Area", "Monthly Demand", "Shading", "Max kWp"]
    ]
    for b in buildings:
        usable = b.gross_roof_area * (b.usable_roof_percentage / 100.0)
        max_c = b.solar_analysis.max_pv_capacity_kwp if b.solar_analysis else min(usable / settings.DEFAULT_AREA_PER_KWP, b.max_eligible_kwp) if b.max_eligible_kwp is not None else usable / settings.DEFAULT_AREA_PER_KWP
        b_table_data.append([
            Paragraph(escape(b.name), style_body),
            Paragraph(escape(b.category), style_body),
            f"{b.gross_roof_area:,.0f} m²",
            f"{usable:,.0f} m²",
            f"{b.monthly_consumption_kwh:,.0f} kWh",
            b.shading_category,
            f"{max_c:.1f} kWp"
        ])

    t_b = Table(b_table_data, colWidths=[110, 74, 60, 60, 75, 55, 70], repeatRows=1)
    t_b.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), c_forest),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 8.5),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, c_light]),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ('ALIGN', (2, 0), (-1, -1), 'RIGHT'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    story.append(t_b)
    story.append(Spacer(1, 12))

    # ================= 3. BUDGET OPTIMIZATION RESULTS =================
    if latest_run and latest_run.allocations_json:
        story.append(Paragraph("3. Budget-Constrained Optimization Allocation", style_h1))
        story.append(Paragraph(
            f"Results of global Multiple-Choice Knapsack solver under objective: <b>{latest_run.objective}</b>. "
            f"The solver evaluated non-linear diminishing returns where generation exceeding daytime load yields lower export revenue.",
            style_body
        ))

        alloc_data = [
            ["Building", "Capacity", "Capex", "Annual Gen", "Annual Savings", "Payback", "Status"]
        ]
        for item in latest_run.allocations_json:
            is_sel = item.get("is_selected", False)
            alloc_data.append([
                Paragraph(escape(item.get("building_name", "")), style_body),
                f"{item.get('recommended_capacity_kwp', 0):.1f} kWp",
                f"₹{item.get('estimated_cost_inr', 0):,.0f}",
                f"{item.get('expected_annual_generation_kwh', 0):,.0f} kWh",
                f"₹{item.get('expected_annual_savings_inr', 0):,.0f}",
                f"{item.get('payback_years', '—')} yrs" if is_sel else "—",
                "SELECTED" if is_sel else "DEFERRED"
            ])

        t_alloc = Table(alloc_data, colWidths=[114, 60, 65, 75, 75, 55, 60], repeatRows=1)
        t_alloc.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), c_forest),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8.5),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, c_light]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('ALIGN', (1, 0), (-2, -1), 'RIGHT'),
            ('ALIGN', (-1, 0), (-1, -1), 'CENTER'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(t_alloc)
        story.append(Spacer(1, 10))

        # Explainability Breakdown
        story.append(Paragraph("<b>Explainable Allocation Rationales:</b>", style_h2))
        for item in latest_run.allocations_json:
            status = "Selected" if item.get("is_selected") else "Excluded/Deferred"
            reasons = item.get("decision_reasons", [])
            bullets = " • ".join(reasons) if reasons else item.get("shade_impact_summary", "")
            story.append(Paragraph(
                f"<b>{escape(str(item.get('building_name')))} ({status}):</b> {escape(bullets).replace('₹', 'INR ')}",
                style_body
            ))

    # ================= 4. BASELINE COMPARISON =================
    if latest_run:
        story.append(Spacer(1, 8))
        story.append(Paragraph("4. Optimized Portfolio vs Naive Baseline Comparison", style_h1))
        comp_data = [
            ["Metric", "Optimized Plan", "Naive Baseline Plan", "Differential / Lift"],
            [
                "Invested Capex",
                f"₹{latest_run.total_allocated_inr:,.0f}",
                f"₹{latest_run.baseline_allocated_inr:,.0f}",
                f"₹{latest_run.total_allocated_inr - latest_run.baseline_allocated_inr:,.0f}"
            ],
            [
                "Annual Bill Savings",
                f"₹{latest_run.total_annual_savings_inr:,.0f}",
                f"₹{latest_run.baseline_savings_inr:,.0f}",
                f"+₹{latest_run.total_annual_savings_inr - latest_run.baseline_savings_inr:,.0f} (+{latest_run.savings_lift_pct:.1f}%)"
            ],
            [
                "Installed Capacity",
                f"{latest_run.total_capacity_kwp:.1f} kWp",
                f"{latest_run.baseline_capacity_kwp:.1f} kWp",
                f"{latest_run.total_capacity_kwp - latest_run.baseline_capacity_kwp:+.1f} kWp"
            ],
            [
                "Annual Generation",
                f"{latest_run.total_annual_generation_kwh:,.0f} kWh",
                f"{latest_run.baseline_generation_kwh:,.0f} kWh",
                f"{latest_run.total_annual_generation_kwh - latest_run.baseline_generation_kwh:+,.0f} kWh"
            ]
        ]
        t_comp = Table(comp_data, colWidths=[120, 120, 120, 144], repeatRows=1)
        t_comp.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#334155")),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8.5),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, c_light]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('ALIGN', (1, 0), (-1, -1), 'RIGHT'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(t_comp)
        story.append(Spacer(1, 10))

    # ================= 5. SMART LOAD SCHEDULING =================
    if activities and include_load_shifting:
        story.append(Paragraph("5. Smart Electricity Scheduling Recommendations", style_h1))
        story.append(Paragraph(
            "Operating windows below use the project's scheduling engine results where available. "
            "Confirm equipment and staffing constraints before changing operations.",
            style_body
        ))
        act_data = [
            ["Activity Name", "Power Draw", "Current Timing", "Recommended Timing", "Solar Absorbed"]
        ]
        shifts = {item.activity_id: item for item in scheduling_result.recommendations} if scheduling_result else {}
        for a in activities:
            shift = shifts.get(a.id)
            orig_h = shift.original_window if shift else f"{a.preferred_hour:02d}:00"
            rec_h = shift.recommended_window if shift else "Not calculated"
            absorbed = f"{shift.additional_solar_absorbed_kwh:.1f} kWh/session" if shift else "Not calculated"
            act_data.append([Paragraph(escape(a.name), style_body), f"{a.power_kw:.1f} kW", orig_h, rec_h, absorbed])

        t_act = Table(act_data, colWidths=[134, 70, 90, 110, 100], repeatRows=1)
        t_act.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), c_forest),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8.5),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, c_light]),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(t_act)
        story.append(Spacer(1, 10))

    # ================= 6. DATA SOURCES, ASSUMPTIONS & DISCLAIMER =================
    story.append(Paragraph("6. Assumptions, Data Sources & Regulatory Disclaimers", style_h1))
    sources = sorted({b.solar_analysis.irradiance_source for b in buildings if b.solar_analysis and b.solar_analysis.irradiance_source})
    irradiance_text = escape("; ".join(sources)) if sources else "No saved irradiance analysis"
    assumptions = latest_run.explanations_json.get("assumptions", {}) if latest_run and isinstance(latest_run.explanations_json, dict) else {}
    tariff_val = assumptions.get("tariff_rate", project.tariff_rate)
    export_tariff_val = assumptions.get("export_tariff", project.export_tariff)
    notes_list = [
        f"<b>Solar Irradiance:</b> {irradiance_text}.",
        f"<b>Economic Tariffs:</b> Grid displacement tariff: INR {tariff_val:.2f}/kWh; Export tariff: INR {export_tariff_val:.2f}/kWh.",
        f"<b>Grid Emission Baseline:</b> Central Electricity Authority (CEA) factor of {project.co2_factor} kg CO2/kWh.",
        "<b>System Performance Ratio:</b> 75% standard derate accounting for inverter efficiency, temperature derating, soiling, and cabling.",
        "<b>Disclaimer:</b> This report represents a preliminary decision-support assessment and screening tool. "
        "It does not constitute certified structural engineering, electrical single-line diagram (SLD) approval, "
        "or statutory distribution company (DISCOM) interconnection approval. Prior to capital procurement, "
        "an on-site structural audit and DISCOM transformer capacity verification must be performed."
    ]
    for n in notes_list:
        story.append(Paragraph(f"• {n}", style_body))

    if include_features:
        assessments = db.query(FeatureAssessment).filter(FeatureAssessment.project_id == project_id).order_by(FeatureAssessment.created_at.desc(), FeatureAssessment.id.desc()).all()
        append_feature_sections(story, assessments, style_h2, style_body, style_caption, include_scenarios)

    if notes and notes.strip():
        story.append(Spacer(1, 12))
        story.append(Paragraph("Project Review Notes", style_h1))
        story.append(Paragraph(escape(notes.strip()).replace("\n", "<br/>"), style_body))

    doc.build(story, canvasmaker=NumberedCanvas)

    file_size = os.path.getsize(file_path)

    # Save to storage provider (Amazon S3 if enabled, local filesystem fallback)
    from app.services.storage.s3_adapter import storage_adapter
    storage_url, provider_name, is_cloud = storage_adapter.save_report_file(file_path, filename)

    report_record = GeneratedReport(
        project_id=project.id,
        filename=filename,
        file_path=file_path,
        file_size_bytes=file_size
    )
    db.add(report_record)
    db.commit()
    db.refresh(report_record)

    return report_record
